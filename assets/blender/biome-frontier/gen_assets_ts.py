"""Writes game/src/zones/biome-frontier/assets.gen.ts from assets/manifest.biome-frontier.json.

python3 gen_assets_ts.py   (run after uploading; entries without a url are left as "pending:<key>")
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
man_path = os.path.join(ROOT, "assets", "manifest.biome-frontier.json")
KEYS = ["jungle_tree", "palm", "giant_leaf_plants", "waterfall_cliff", "canyon_rocks", "dig_site", "corals", "pier", "field_station",
        "rope_bridge", "signposts", "trail_gate", "toucan", "tree_frog", "morpho", "tortoise", "horned_lizard", "saguaro", "sea_turtle",
        "clownfish", "sea_star", "jungle_floor", "sand", "canyon_floor", "water_n", "ambience"]
IMG = ["toucan", "tree_frog", "morpho", "tortoise", "horned_lizard", "saguaro", "sea_turtle", "clownfish", "sea_star"]
FILES = {k: k + ".glb" for k in KEYS[:21]}
FILES.update({"jungle_floor": "jungle_floor.jpg", "sand": "sand.jpg", "canyon_floor": "canyon_floor.jpg", "water_n": "water_n.jpg",
              "ambience": "bf_ambience.mp3"})
FILES.update({"img_" + k: "icon_" + k + ".jpg" for k in IMG})
man = json.load(open(man_path)) if os.path.exists(man_path) else []
by_key = {e.get("key"): e for e in man}
urls = {k: by_key.get(k, {}).get("url") or "pending:" + k for k in FILES}
out = ["// GENERATED by assets/blender/biome-frontier/gen_assets_ts.py from assets/manifest.biome-frontier.json - do not edit.",
       "// Library URLs of the district's original assets (props defaults), and their local file names (dev harness).",
       "export const ASSETS = {"]
out += [f'  {k}: "{u}",' for k, u in urls.items()]
out += ["};", "", "export const ASSET_FILES: Record<keyof typeof ASSETS, string> = {"]
out += [f'  {k}: "{f}",' for k, f in FILES.items()]
out += ["};", ""]
p = os.path.join(ROOT, "game", "src", "zones", "biome-frontier", "assets.gen.ts")
open(p, "w").write("\n".join(out))
print("wrote", p, sum(1 for u in urls.values() if not u.startswith("pending")), "urls")
